"""Markdown / JSON reports for journal replay."""
from __future__ import annotations

import json
from dataclasses import asdict
from pathlib import Path
from typing import Any

from algoflat.replay.full_session import FullSessionReplayResult, ReplayClosedTrade
from algoflat.replay.loader import DayJournal, JournalClosedTrade, JournalSignal
from algoflat.replay.session import SessionReplayResult
from algoflat.replay.validate import RevalidationReport


def write_validate_report(
    report: RevalidationReport,
    journal: DayJournal,
    *,
    out_md: Path | None = None,
    out_json: Path | None = None,
) -> tuple[Path | None, Path | None]:
    md = _validate_markdown(report, journal)
    if out_md:
        out_md.parent.mkdir(parents=True, exist_ok=True)
        out_md.write_text(md)
    if out_json:
        payload: dict[str, Any] = {
            "replay_mode": "journal_validate",
            "report": asdict(report),
            "funnel": asdict(journal.funnel),
        }
        out_json.parent.mkdir(parents=True, exist_ok=True)
        out_json.write_text(json.dumps(payload, indent=2, default=str))
    return out_md, out_json


def _validate_markdown(report: RevalidationReport, journal: DayJournal) -> str:
    f = journal.funnel
    lines = [
        f"# Journal Replay — validate mode — {journal.underlying} {report.day}",
        "",
        "## Live funnel (from Postgres journal)",
        "",
        f"| Metric | Count |",
        f"|--------|------:|",
        f"| strategy_decision scans | {f.strategy_decisions} |",
        f"| candidate_signals | {f.candidate_signals} |",
        f"| validator_passed | {f.validator_passed} |",
        f"| orders_placed | {f.orders_placed} |",
        f"| orders_filled | {f.orders_filled} |",
        f"| closed_trades | {f.closed_trades} |",
        f"| entry_skipped | {f.entry_skipped_events} |",
        "",
        "## Validator revalidation (current config vs journal)",
        "",
        f"- Signals in journal: **{report.total}**",
        f"- Comparable (had validation row): **{report.comparable}**",
        f"- Agreement: **{report.agrees}/{report.comparable}** ({report.agreement_pct:.1f}%)",
        f"- New passes (replay OK, live blocked): **{len(report.new_passes)}**",
        f"- New fails (replay blocked, live OK): **{len(report.new_fails)}**",
        "",
        "### Limitations",
        "",
    ]
    for lim in report.limitations:
        lines.append(f"- {lim}")
    lines.extend(["", "### Disagreements (first 30)", ""])
    if not report.disagreements:
        lines.append("_None — current validator matches journal._")
    else:
        lines.append(
            "| Time | Setup | Tsym | Live | Replay | Live reasons | Replay reasons |"
        )
        lines.append("|------|-------|------|------|--------|--------------|----------------|")
        for r in report.disagreements[:30]:
            live = "PASS" if r.live_passed else "FAIL"
            replay = "PASS" if r.replay_passed else "FAIL"
            lr = ", ".join(r.live_reasons[:3]) or "—"
            rr = ", ".join(r.replay_reasons[:3]) or "—"
            lines.append(
                f"| {r.ts_ist[11:]} | {r.setup_type} | {r.tsym} | {live} | {replay} | {lr} | {rr} |"
            )
    lines.extend(
        [
            "",
            "## Next steps",
            "",
            "- `validate` catches config drift before live.",
            "- Use `--mode replay` (Phase 2) to replay full scan schedule from `strategy_decision`.",
            "- Target: **>95%** validator agreement without config changes.",
            "",
            "_Generated by `scripts/journal_replay.py`_",
        ]
    )
    return "\n".join(lines) + "\n"


def write_replay_report(
    result: SessionReplayResult,
    journal: DayJournal,
    comparison: dict[str, Any],
    *,
    out_md: Path | None = None,
    out_json: Path | None = None,
) -> tuple[Path | None, Path | None]:
    md = _replay_markdown(result, journal, comparison)
    if out_md:
        out_md.parent.mkdir(parents=True, exist_ok=True)
        out_md.write_text(md)
    if out_json:
        payload: dict[str, Any] = {
            "replay_mode": "journal_replay",
            "day": str(result.day),
            "underlying": result.underlying,
            "schedule_source": result.schedule_source,
            "scans_run": result.scans_run,
            "signals_seen": result.signals_seen,
            "validator_passed": result.validator_passed,
            "skips": result.skips,
            "comparison": comparison,
            "decisions": result.decisions,
            "funnel": asdict(journal.funnel),
        }
        out_json.parent.mkdir(parents=True, exist_ok=True)
        out_json.write_text(json.dumps(payload, indent=2, default=str))
    return out_md, out_json


def _replay_markdown(
    result: SessionReplayResult,
    journal: DayJournal,
    comparison: dict[str, Any],
) -> str:
    f = journal.funnel
    lines = [
        f"# Journal Replay — replay mode — {result.underlying} {result.day}",
        "",
        "## Live funnel (from Postgres journal)",
        "",
        "| Metric | Live | Replay |",
        "|--------|-----:|-------:|",
        f"| strategy_decision scans | {f.strategy_decisions} | {result.scans_run} |",
        f"| candidate_signals | {f.candidate_signals} | {result.signals_seen} |",
        f"| validator_passed | {f.validator_passed} | {result.validator_passed} |",
        f"| closed_trades | {f.closed_trades} | — |",
        "",
        "## Signal parity",
        "",
        f"- Schedule source: **{result.schedule_source}**",
        f"- Matched signals: **{comparison.get('matched_count', 0)}**",
        f"- Live only: **{comparison.get('live_only_count', 0)}**",
        f"- Replay only: **{comparison.get('replay_only_count', 0)}**",
        f"- Validator agreement (matched): **{comparison.get('validator_agreement_pct', 0)}%**",
        "",
    ]
    mismatches = comparison.get("validator_mismatch") or []
    if mismatches:
        lines.extend(["### Validator mismatches (first 20)", ""])
        lines.append(
            "| Setup | Side | Tsym | Live | Replay | Live reasons | Replay reasons |"
        )
        lines.append("|-------|------|------|------|--------|--------------|----------------|")
        for m in mismatches[:20]:
            lr = ", ".join((m.get("live_rejections") or [])[:2]) or "—"
            rr = ", ".join((m.get("replay_rejections") or [])[:2]) or "—"
            lines.append(
                f"| {m.get('setup_type')} | {m.get('side')} | {m.get('tsym')} | "
                f"{'PASS' if m.get('live_validator_passed') else 'FAIL'} | "
                f"{'PASS' if m.get('replay_validator_passed') else 'FAIL'} | {lr} | {rr} |"
            )
    else:
        lines.append("_No validator mismatches among matched signals._")

    live_only = comparison.get("live_only") or []
    if live_only:
        lines.extend(["", "### Live-only signals (first 15)", ""])
        for s in live_only[:15]:
            lines.append(
                f"- {s.get('ts_ist', '?')} {s.get('setup_type')} {s.get('side')} "
                f"{s.get('tsym')} validator={'PASS' if s.get('validator_passed') else 'FAIL'}"
            )

    replay_only = comparison.get("replay_only") or []
    if replay_only:
        lines.extend(["", "### Replay-only signals (first 15)", ""])
        for s in replay_only[:15]:
            lines.append(
                f"- {s.get('ts_ist', '?')} {s.get('setup_type')} {s.get('side')} "
                f"{s.get('tsym')} validator={'PASS' if s.get('validator_passed') else 'FAIL'}"
            )

    if result.skips:
        lines.extend(["", "### Router skips (top reasons)", ""])
        for reason, count in sorted(result.skips.items(), key=lambda x: -x[1])[:10]:
            lines.append(f"- {reason}: {count}")

    lines.extend(
        [
            "",
            "## Next steps",
            "",
            "- Target: **>90%** matched signals with **>95%** validator agreement.",
            "- Use `--mode full` (Phase 3) for trade-level exit replay.",
            "",
            "_Generated by `scripts/journal_replay.py`_",
        ]
    )
    return "\n".join(lines) + "\n"


def journal_closed_trade_row(trade: JournalClosedTrade) -> dict[str, Any]:
    entry = trade.entry_ts
    exit_ts = trade.exit_ts
    if entry.tzinfo is None:
        from zoneinfo import ZoneInfo

        entry = entry.replace(tzinfo=ZoneInfo("UTC"))
    if exit_ts.tzinfo is None:
        from zoneinfo import ZoneInfo

        exit_ts = exit_ts.replace(tzinfo=ZoneInfo("UTC"))
    return {
        "entry_ist": entry.strftime("%Y-%m-%d %H:%M:%S"),
        "exit_ist": exit_ts.strftime("%Y-%m-%d %H:%M:%S"),
        "entry_epoch": entry.timestamp(),
        "tsym": trade.tsym,
        "side": trade.side,
        "setup_type": trade.setup_type,
        "lots": max(1, trade.quantity // 65) if trade.quantity else 1,
        "qty": trade.quantity,
        "pnl": trade.pnl,
        "exit_reason": trade.exit_reason,
        "mode": trade.mode,
    }


def replay_closed_trade_row(trade: ReplayClosedTrade) -> dict[str, Any]:
    entry = trade.entry_ts
    exit_ts = trade.exit_ts
