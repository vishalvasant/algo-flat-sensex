def write_full_report(
    result: FullSessionReplayResult,
    journal: DayJournal,
    signal_comparison: dict[str, Any],
    trade_comparison: dict[str, Any],
    *,
    out_md: Path | None = None,
    out_json: Path | None = None,
) -> tuple[Path | None, Path | None]:
    md = _full_markdown(result, journal, signal_comparison, trade_comparison)
    if out_md:
        out_md.parent.mkdir(parents=True, exist_ok=True)
        out_md.write_text(md)
    if out_json:
        payload: dict[str, Any] = {
            "replay_mode": "journal_full",
            "day": str(result.day),
            "underlying": result.underlying,
            "schedule_source": result.schedule_source,
            "scans_run": result.scans_run,
            "signals_seen": result.signals_seen,
            "validator_passed": result.validator_passed,
            "entries": result.entries,
            "closed_trades": len(result.closed),
            "realized_pnl": float(result.realized_pnl),
            "signal_comparison": signal_comparison,
            "trade_comparison": trade_comparison,
            "funnel": asdict(journal.funnel),
        }
        out_json.parent.mkdir(parents=True, exist_ok=True)
        out_json.write_text(json.dumps(payload, indent=2, default=str))
    return out_md, out_json


def _full_markdown(
    result: FullSessionReplayResult,
    journal: DayJournal,
    signal_comparison: dict[str, Any],
    trade_comparison: dict[str, Any],
) -> str:
    f = journal.funnel
    lines = [
        f"# Journal Replay — full mode — {result.underlying} {result.day}",
        "",
        "## Funnel",
        "",
        "| Metric | Live | Replay |",
        "|--------|-----:|-------:|",
        f"| strategy_decision scans | {f.strategy_decisions} | {result.scans_run} |",
        f"| candidate_signals | {f.candidate_signals} | {result.signals_seen} |",
        f"| validator_passed | {f.validator_passed} | {result.validator_passed} |",
        f"| closed_trades | {f.closed_trades} | {len(result.closed)} |",
        f"| realized P&L | — | ₹{result.realized_pnl:,.0f} |",
        "",
        "## Signal parity",
        "",
        f"- Matched: **{signal_comparison.get('matched_count', 0)}**",
        f"- Validator agreement: **{signal_comparison.get('validator_agreement_pct', 0)}%**",
        "",
        "## Trade parity",
        "",
        f"- Tolerance: **{trade_comparison.get('tolerance_sec', 120)}s**",
        f"- Matched: **{trade_comparison.get('matched_count', 0)}** / "
        f"{trade_comparison.get('live_count', 0)} live "
        f"({trade_comparison.get('match_rate_pct', 0)}%)",
        f"- P&L direction agreement: **{trade_comparison.get('pnl_direction_agreement_pct', 0)}%**",
        f"- Live only: **{trade_comparison.get('live_only_count', 0)}**",
        f"- Replay only: **{trade_comparison.get('replay_only_count', 0)}**",
        "",
    ]
    matched = trade_comparison.get("matched") or []
    if matched:
        lines.extend(["### Matched trades", ""])
        lines.append("| Contract | Setup | Live entry | Replay entry | Δsec | Live P&L | Replay P&L |")
        lines.append("|---|---|---|---|---:|---:|---:|")
        for m in matched[:30]:
            lines.append(
                f"| {m.get('tsym')} | {m.get('setup_type')} | "
                f"{str(m.get('live_entry', ''))[11:]} | {str(m.get('replay_entry', ''))[11:]} | "
                f"{m.get('entry_delta_sec')} | ₹{m.get('live_pnl', 0):,.0f} | "
                f"₹{m.get('replay_pnl', 0):,.0f} |"
            )
        lines.append("")

    live_only = trade_comparison.get("live_only") or []
    if live_only:
        lines.extend(["### Live-only trades", ""])
        for t in live_only[:20]:
            lines.append(
                f"- {t.get('entry_ist', '?')[11:]} `{t.get('tsym')}` "
                f"{t.get('setup_type')} P&L=₹{t.get('pnl', 0):,.0f} "
                f"reason={t.get('exit_reason')}"
            )
        lines.append("")

    replay_only = trade_comparison.get("replay_only") or []
    if replay_only:
        lines.extend(["### Replay-only trades", ""])
        for t in replay_only[:20]:
            lines.append(
                f"- {t.get('entry_ist', '?')[11:]} `{t.get('tsym')}` "
                f"{t.get('setup_type')} P&L=₹{t.get('pnl', 0):,.0f} "
                f"reason={t.get('exit_reason')}"
            )
        lines.append("")

    lines.extend(
        [
            "_Generated by `scripts/journal_replay.py --mode full`_",
        ]
    )
    return "\n".join(lines) + "\n"


def journal_signal_row(sig: JournalSignal) -> dict[str, Any]:
    """Normalize journal signal for compare_signal_decisions."""
    ts = sig.ts
    if ts.tzinfo is None:
        from zoneinfo import ZoneInfo

        ts = ts.replace(tzinfo=ZoneInfo("UTC"))
    return {
        "ts_ist": ts.strftime("%Y-%m-%d %H:%M:%S"),
        "ts_epoch": ts.timestamp(),
        "setup_type": sig.setup_type,
        "side": sig.side,
        "tsym": sig.tsym,
        "validator_passed": bool(sig.validator_passed),
        "rejection_reasons": list(sig.rejection_reasons),
        "order_filled": sig.order_filled,
    }


def write_schedule_report(journal: DayJournal, *, out_md: Path) -> None:
    """Phase 2 preview — scan schedule stats only."""
    scans = journal.scans
    if not scans:
        body = "_No strategy_decision events for this day._"
    else:
        gaps = []
        for i in range(1, min(len(scans), 500)):
            delta = (scans[i].ts - scans[i - 1].ts).total_seconds()
            gaps.append(delta)
        avg_gap = sum(gaps) / len(gaps) if gaps else 0
        body = (
            f"- Scan events: **{len(scans)}**\n"
            f"- First: {scans[0].ts.strftime('%H:%M:%S')}\n"
            f"- Last: {scans[-1].ts.strftime('%H:%M:%S')}\n"
            f"- Avg gap: {avg_gap:.1f}s"
        )
    out_md.parent.mkdir(parents=True, exist_ok=True)
    out_md.write_text(
        f"# Journal Replay — scan schedule — {journal.underlying} {journal.day}\n\n{body}\n"
    )
